import { env } from '../config/env.js';
import { serviceUnavailable } from '../lib/errors.js';

// AutoMind diagnostic-device adapter. The API talks to an AutoMind gateway
// (the shop-side bridge that owns the OBD/DoIP link) over HTTPS:
//
//   GET  {gateway}/v1/devices/{serial}                -> identity + online flag
//   GET  {gateway}/v1/devices/{serial}/capabilities   -> protocols, modules, PIDs, commands
//   POST {gateway}/v1/devices/{serial}/commands       -> { commandRef, status, result? }
//   GET  {gateway}/v1/commands/{commandRef}           -> { status, result?, error? }
//
// Devices may also push telemetry and command results to
// POST /api/v1/automind/ingest (HMAC signed). Without a configured gateway the
// adapter reports "not_configured" and technicians use manual entry; no
// readings are ever generated by this code.

export const STANDARD_COMMANDS = {
  READ_VIN: { privileged: false, description: 'Read VIN from the vehicle' },
  READ_DTCS: { privileged: false, description: 'Read stored, pending and permanent DTCs from all reachable modules' },
  READ_FREEZE_FRAME: { privileged: false, description: 'Read freeze-frame data for a DTC' },
  READ_PIDS: { privileged: false, description: 'Read the requested live data PIDs' },
  CLEAR_DTCS: { privileged: true, description: 'Clear DTCs and reset readiness monitors' },
  ACTUATOR_TEST: { privileged: true, description: 'Bi-directional component control' }
};

const configured = () => Boolean(env.automind.gatewayUrl);

const call = async (method, path, body) => {
  if (!configured()) {
    throw serviceUnavailable('AutoMind gateway is not configured. Use manual diagnostic entry.', 'AUTOMIND_NOT_CONFIGURED');
  }
  const ctrl = new AbortController();
  const timer = setTimeout(() => ctrl.abort(), 20000);
  try {
    const res = await fetch(`${env.automind.gatewayUrl.replace(/\/$/, '')}${path}`, {
      method,
      headers: { 'Content-Type': 'application/json', Authorization: `Bearer ${env.automind.apiKey}` },
      body: body ? JSON.stringify(body) : undefined,
      signal: ctrl.signal
    });
    const data = await res.json().catch(() => ({}));
    if (!res.ok) {
      throw serviceUnavailable(`AutoMind gateway error: ${data?.message || `HTTP ${res.status}`}`, 'AUTOMIND_GATEWAY_ERROR');
    }
    return data;
  } catch (err) {
    if (err.status) throw err;
    throw serviceUnavailable(`AutoMind gateway unreachable (${err.name === 'AbortError' ? 'timeout' : err.message})`, 'AUTOMIND_UNREACHABLE');
  } finally {
    clearTimeout(timer);
  }
};

export const automind = {
  configured,
  status: () => ({
    configured: configured(),
    gatewayUrl: configured() ? env.automind.gatewayUrl.replace(/\/\/([^@/]*@)/, '//') : null,
    ingestConfigured: Boolean(env.automind.ingestSecret),
    mode: configured() ? 'gateway' : 'manual_entry_only'
  }),
  getDevice: (serial) => call('GET', `/v1/devices/${encodeURIComponent(serial)}`),
  discoverCapabilities: (serial) => call('GET', `/v1/devices/${encodeURIComponent(serial)}/capabilities`),
  sendCommand: (serial, { command, params, vin, correlationId }) =>
    call('POST', `/v1/devices/${encodeURIComponent(serial)}/commands`, { command, params, vehicle: vin ? { vin } : undefined, correlationId }),
  getCommand: (ref) => call('GET', `/v1/commands/${encodeURIComponent(ref)}`)
};
